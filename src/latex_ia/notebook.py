"""Generate a Jupyter notebook from the paper's units and generated code."""

from __future__ import annotations

import json
import re
from pathlib import Path

from latex_ia.models import Manifest, Unit


def _md_cell(source: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": source}


def _code_cell(source: str) -> dict:
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": source,
    }


def _latex_to_md(raw: str) -> str:
    """Strip outer LaTeX environment wrappers, keep content."""
    raw = re.sub(r"\\begin\{[^}]+\}", "", raw)
    raw = re.sub(r"\\end\{[^}]+\}", "", raw)
    return raw.strip()


def generate_notebook(units: list[Unit], manifest: Manifest, title: str = "Paper") -> dict:
    cells: list[dict] = [
        _md_cell(f"# {title}\n\n_Generated by [tex2code](https://github.com/iblanco/latex-ia)_")
    ]

    current_section: str = ""
    for unit in units:
        section = " › ".join(unit.section_path) if unit.section_path else ""
        if section and section != current_section:
            current_section = section
            cells.append(_md_cell(f"## {section}"))

        entry = manifest.entries.get(unit.id)
        role = entry.role.value if entry else "unknown"
        cells.append(_md_cell(f"**`{unit.id}`** _{role}_\n\n```latex\n{unit.raw.strip()}\n```"))

        if entry and entry.code:
            for path_str in entry.code:
                try:
                    src = Path(path_str).read_text(encoding="utf-8")
                    cells.append(_code_cell(src))
                except OSError:
                    pass

        if entry and entry.tests:
            for path_str in entry.tests:
                try:
                    src = Path(path_str).read_text(encoding="utf-8")
                    cells.append(_code_cell(f"# Tests\n{src}"))
                except OSError:
                    pass

    return {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python", "version": "3.11.0"},
        },
        "cells": cells,
    }


def write_notebook(units: list[Unit], manifest: Manifest, title: str = "Paper") -> Path:
    out = Path(".tex2code/notebook.ipynb")
    out.parent.mkdir(parents=True, exist_ok=True)
    nb = generate_notebook(units, manifest, title)
    out.write_text(json.dumps(nb, indent=2), encoding="utf-8")
    return out
